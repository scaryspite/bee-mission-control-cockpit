const pose = (name) => ({
  primary: asset(`beeps-pose-${name}.png`),
  alternate: asset(`beeps-pose-${name}-alt.png`),
  animate: false,
  scale: 1,
  groundRatio: poseGroundRatios[name] ?? 0,
});

const station = (config) => ({
  ...config,
  composition: config.composition ?? (config.renderAsset === false ? "room-owned" : "prop-owned"),
  pose: config.poseAsset
    ? {
        primary: asset(config.poseAsset),
        alternate: config.poseAlternateAsset ? asset(config.poseAlternateAsset) : null,
        animate: config.poseAnimate ?? false,
        scale: config.poseScale ?? 1,
        groundRatio: config.poseGroundRatio ?? 0,
      }
    : pose(config.pose),
  asset: config.asset ? asset(config.asset) : null,
  usedAsset: config.usedAsset ? asset(config.usedAsset) : null,
  heldProp: config.heldProp ? asset(config.heldProp) : null,
});

